def call_gemini_api(
    contents: List[Dict[str, Any]],
    api_key: str,
    model: str = "gemini-3.8-flash-high",
    system_instruction: Optional[str] = None,
    response_json: bool = False
) -> str:
    """
    Direct HTTPS REST call to Google Gemini API (no external heavy SDK needed).
    Strictly uses the gemini-3.8-flash-high endpoint with no fallbacks.
    """
    key = resolve_gemini_api_key(api_key)
    if not key:
        raise ValueError("Gemini API key is required. Please add your key in the AI Setup modal or set GEMINI_API_KEY.")

    target_model = normalize_model_name(model)

    payload: Dict[str, Any] = {
        "contents": contents,
        "generationConfig": {
            "temperature": 0.2,
            "maxOutputTokens": 8192
        }
    }
    if response_json:
        payload["generationConfig"]["responseMimeType"] = "application/json"

    if system_instruction:
        payload["systemInstruction"] = {
            "parts": [{"text": system_instruction}]
        }

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{target_model}:generateContent?key={key}"
    
    try:
        resp = requests.post(url, json=payload, headers={"Content-Type": "application/json"}, timeout=120)
        
        if resp.status_code == 200:
            data = resp.json()
            candidates = data.get("candidates", [])
            if not candidates:
                raise ValueError("No response generated by Gemini model.")
            parts = candidates[0].get("content", {}).get("parts", [])
            full_text = "".join([p.get("text", "") for p in parts])
            return full_text
            
        elif resp.status_code in [400, 404]:
            raise ValueError(f"Model '{target_model}' request failed ({resp.status_code}): {resp.text}")
        elif resp.status_code == 403:
            raise ValueError("Gemini API key is invalid or unauthorized. Please verify your Google AI Studio key.")
        elif resp.status_code == 429:
            raise ValueError("Gemini API rate limit exceeded. Please wait a moment before trying again.")
        else:
            raise ValueError(f"Gemini API error ({resp.status_code}): {resp.text}")
            
    except requests.exceptions.Timeout:
        raise ValueError("Gemini API request timed out. Please try again.")
    except requests.exceptions.RequestException as e:
        raise ValueError(f"Failed to generate content with Gemini. Network error: {str(e)}")


