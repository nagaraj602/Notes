def resolve_gemini_api_key(client_key: Optional[str] = None) -> str:
    """
    Resolves the Gemini API key from:
    1. Client-supplied key (via header or request body)
    2. Server environment variable GEMINI_API_KEY
    3. Persistent token file on server (/app/data/notes/.gemini_api_key)
    """
    if client_key and client_key.strip():
        return client_key.strip()

    env_key = os.getenv("GEMINI_API_KEY", "").strip()
    if env_key:
        return env_key

    # Check file locations
    candidate_paths = [
        "/app/data/notes/.gemini_api_key",
        os.path.join(os.path.dirname(__file__), "..", "..", ".gemini_api_key")
    ]
    try:
        from app.config import NOTES_DIR
        if NOTES_DIR:
            candidate_paths.insert(0, os.path.join(NOTES_DIR, ".gemini_api_key"))
    except Exception:
        pass

    for cp in candidate_paths:
        if os.path.exists(cp):
            try:
                with open(cp, "r", encoding="utf-8") as f:
                    k = f.read().strip()
                    if k:
                        return k
            except Exception:
                pass

    return ""

def save_gemini_api_key(api_key: str) -> bool:
    """Saves Gemini API key to persistent server storage if available."""
    clean = api_key.strip()
    if not clean:
        return False
    target_paths = ["/app/data/notes/.gemini_api_key"]
    try:
        from app.config import NOTES_DIR
        if NOTES_DIR and os.path.exists(NOTES_DIR):
            target_paths.insert(0, os.path.join(NOTES_DIR, ".gemini_api_key"))
    except Exception:
        pass

    for tp in target_paths:
        try:
            os.makedirs(os.path.dirname(tp), exist_ok=True)
            with open(tp, "w", encoding="utf-8") as f:
                f.write(clean)
            return True
        except Exception as e:
            logger.warning(f"Could not save Gemini key to {tp}: {e}")
    return False

